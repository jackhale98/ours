// Fails if any dependency uses a license outside scripts/license-policy.json.
// Production dependencies (shipped to users or run on the Worker) must use an
// allowed license. Dev-only tooling may also use a reviewed exception.
// Writes THIRD_PARTY_NOTICES.md listing production dependencies.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const policy = JSON.parse(readFileSync(new URL('./license-policy.json', import.meta.url), 'utf8'));
const list = (args) =>
  JSON.parse(execFileSync('pnpm', ['licenses', 'list', '--json', ...args], { encoding: 'utf8' }));

/** An SPDX "A OR B" expression is acceptable if any alternative is allowed. */
const allowed = (license) =>
  policy.allow.includes(license) ||
  license
    .replace(/[()]/g, '')
    .split(/\s+OR\s+/)
    .some((l) => policy.allow.includes(l.trim()));

const prod = list(['--prod']);
const all = list([]);
const problems = [];

for (const [license, pkgs] of Object.entries(prod)) {
  if (!allowed(license)) {
    problems.push(`production: ${license} — ${pkgs.map((p) => p.name).join(', ')}`);
  }
}
for (const [license, pkgs] of Object.entries(all)) {
  if (!allowed(license) && !(license in policy.devOnlyExceptions) && !(license in prod)) {
    problems.push(`dev: ${license} — ${pkgs.map((p) => p.name).join(', ')}`);
  }
}

if (process.argv.includes('--notices')) {
  const rows = Object.entries(prod)
    .flatMap(([license, pkgs]) =>
      pkgs.map((p) => ({ name: p.name, version: p.versions.join(', '), license })),
    )
    .sort((a, b) => a.name.localeCompare(b.name));
  const body = [
    '# Third-party notices',
    '',
    'Generated by `pnpm check:licenses --notices`. Production dependencies only.',
    '',
    '| Package | Version | License |',
    '|---|---|---|',
    ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
    '',
    '## Fonts (bundled, SIL Open Font License 1.1, full text in apps/web/src/fonts/OFL.txt)',
    '',
    '- Figtree — Copyright 2022 The Figtree Project Authors (https://github.com/erikdkennedy/figtree)',
    '- Bricolage Grotesque — Copyright 2022 The Bricolage Grotesque Project Authors (https://github.com/ateliertriay/bricolage)',
    '',
    'Latin subsets taken from Fontsource 5.3.0 (`@fontsource-variable/figtree`, `@fontsource-variable/bricolage-grotesque`).',
    '',
    'Build-time data: caniuse-lite (CC-BY-4.0), © Alexis Deveria and contributors.',
    '',
    '## Vendored code',
    '',
    '- `apps/api/src/push/encrypt.ts` and `apps/api/src/push/vapid.ts`: adapted from mycelium-web (https://github.com/jackhale98/mycelium-web), GPL-3.0-or-later, by the same author, relicensed into Ours under AGPL-3.0-or-later (ADR 0010).',
    '',
  ].join('\n');
  writeFileSync('THIRD_PARTY_NOTICES.md', body);
}

if (problems.length) {
  console.error(`License check failed:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}
console.warn('License check passed.');
